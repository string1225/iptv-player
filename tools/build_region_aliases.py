"""Generate province/city/county TV-name aliases from a local upstream pca-code.json.

Source: modood/Administrative-divisions-of-China, 2023-06-30 dataset, WTFPL.
No remote instructions are executed. Ambiguous aliases are resolved by RegionalGroups.
"""
import argparse
import json
import pathlib
import re


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$").replace("\\f", "\\u000c")


def aliases(name):
    if name in ("市辖区", "县", "省直辖县级行政区划", "自治区直辖县级行政区划"):
        return set()
    values = {name}
    short = re.sub(r"(自治县|自治州|自治区|特别行政区|地区|市|县|区|盟|旗)$", "", name)
    if len(short) >= 2:
        values.add(short)
    if name.endswith(("自治县", "自治州")):
        ethnic = r"(?:蒙古族|藏族|壮族|回族|维吾尔族|满族|苗族|彝族|侗族|土家族|瑶族|傣族|布依族|哈尼族|黎族|白族|傈僳族|纳西族|羌族|朝鲜族|哈萨克族|普米族|独龙族|怒族|撒拉族|东乡族|保安族|裕固族|土族|拉祜族|佤族|景颇族|阿昌族|仫佬族|毛南族|水族|仡佬族|达斡尔族|鄂温克族|鄂伦春族)+$"
        simple = re.sub(ethnic, "", short)
        if len(simple) >= 2:
            values.add(simple)
    return values


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("app/src/main/java/com/string/iptv/catalog/RegionNames.kt"))
    args = parser.parse_args()
    data = json.loads(args.input.read_text(encoding="utf-8"))
    rows = []
    for province in data:
        name = province["name"]
        canonical = re.sub(r"(壮族自治区|回族自治区|维吾尔自治区|自治区|省|市)$", "", name)
        names = aliases(name) | {canonical}
        for city in province.get("children", []):
            names |= aliases(city["name"])
            for county in city.get("children", []):
                names |= aliases(county["name"])
        names.discard("")
        rows.append((canonical, names))
    rows.extend([("香港", {"香港", "香港特别行政区", "香港特別行政區"}),
                 ("澳门", {"澳门", "澳門", "澳门特别行政区", "澳門特別行政區"}),
                 ("台湾", {"台湾", "臺灣", "台灣", "台北", "臺北", "新北", "高雄", "台中", "臺中", "台南", "臺南", "桃园", "桃園"})])
    owners = {}
    for canonical, names in rows:
        for name in names:
            owners.setdefault(name, set()).add(canonical)
    for canonical, _ in rows:
        owners[canonical] = {canonical}
    # Compile only unambiguous prefixes. A shorter prefix already recognizes the full name.
    compact = []
    for canonical, names in rows:
        unique = {name for name in names if owners[name] == {canonical}}
        prefixes = []
        for name in sorted(unique, key=lambda value: (len(value), value)):
            if not any(name.startswith(prefix) for prefix in prefixes):
                prefixes.append(name)
        compact.append((canonical, set(prefixes)))
    rows = compact
    lines = ["package com.string.iptv.catalog", "", "// Generated by tools/build_region_aliases.py from modood's 2023-06-30 data (WTFPL).",
             "// https://github.com/modood/Administrative-divisions-of-China", "internal object RegionNames {", "    val aliases = linkedMapOf("]
    for canonical, names in rows:
        lines.append(f'        {kotlin_string(canonical)} to {kotlin_string(" ".join(sorted(names)))}.split(\' \'),')
    lines.extend(["    )", "}", ""])
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(rows)} regions, {sum(len(names) for _, names in rows)} aliases")


if __name__ == "__main__":
    main()
